def classify_prompt(focus: str) -> str:
    """意图/风险分类提示词（LLM 输出结构化 JSON）。"""
    return (
        "你是企业 IT 工单的意图分类与风险分级器。根据下面的工单文本判断：\n"
        "1. intent_type（意图类型），取值只能是：knowledge（知识咨询）、data_query（数据查询）、"
        "change（变更/授权/开通权限）、troubleshoot（故障排查）之一。\n"
        "2. risk_level（风险等级），取值只能是：low、medium、high 之一。凡涉及开通权限、"
        "授权、变更、生产故障、数据处理等一律不能是 low。\n"
        "3. reason：一句话说明判定理由。\n"
        "只输出一个 JSON 对象，不要输出其他内容，格式："
        '{"intent_type":"...","risk_level":"...","reason":"..."}\n\n'
        f"工单文本：{focus}"
    )


def relevance_prompt(title: str, description: str) -> str:
    """建单前相关性确认提示词（不相关才拒绝，LLM 不可用时放行）。"""
    return (
        "你是企业 IT 工单系统的入口校验器。判断用户提交的内容是否属于『企业 IT 工单』"
        "处理范围（如：IT 故障排查、知识库/运维咨询、账号与权限开通回收、数据查询、"
        "网络/系统/数据库相关变更等）。\n"
        "明显不相关的情况（如闲聊、招聘、销售、无关提问）才判为 not_relevant。\n"
        "只输出一个 JSON 对象，不要输出其他内容，格式：\n"
        '{"relevant": true, "reason": "一句话理由"}\n'
        "其中 relevant 取值 true（相关）或 false（不相关）。\n\n"
        f"标题：{title}\n内容：{description}"
    )


def rewrite_prompt(title: str, description: str) -> str:
    """提示词重写提示词：把原始内容整理成简洁结构化任务目标。"""
    return (
        "你是企业 IT 工单系统的内容整理器。把用户提交的原始工单内容改写为简洁、结构化的"
        "任务目标，供下游 Agent 使用。要求：\n"
        "1. 保持原始诉求的关键信息（对象、动作、目标），不增删事实；\n"
        "2. 用 1-2 句话概括核心任务；\n"
        "3. 提取 3~6 个关键词（含可能涉及的用户/账号/主机等实体）。\n"
        "只输出一个 JSON 对象，不要输出其他内容，格式：\n"
        '{"summary": "简洁任务目标", "keywords": ["kw1", "kw2"]}\n\n'
        f"标题：{title}\n内容：{description}"
    )


def followup_relevance_prompt(ticket_title: str, ticket_desc: str,
                              recent_dialogue: str, content: str) -> str:
    """追加提问相关性校验提示词：追加内容与当前工单是否相关。

    相关：追问、补充信息、提供新线索、对处理结果提问等；
    不相关：与工单无关的闲聊、另一个全新任务等。
    """
    return (
        "你是企业 IT 工单系统的对话校验器。用户在已建工单的对话中追加了一条消息，"
        "请判断这条追加消息是否与当前工单相关。\n"
        "判定为『相关』的情况：对工单诉求的追问、补充细节/线索/账号信息、"
        "对 Agent 处理结果的提问、同意或拒绝等。\n"
        "判定为『不相关』的情况：与工单完全无关的闲聊、以及明显属于另一个全新任务"
        "（应建议其新建工单）的内容。\n"
        "只输出一个 JSON 对象，不要输出其他内容，格式：\n"
        '{"relevant": true, "reason": "一句话理由"}\n'
        "其中 relevant 取值 true（相关）或 false（不相关）。\n\n"
        f"工单标题：{ticket_title}\n工单内容：{ticket_desc}\n"
        f"最近对话：{recent_dialogue or '（暂无）'}\n"
        f"追加消息：{content}"
    )
